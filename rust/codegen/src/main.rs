//! Writes the Rust code of the protocol buffers that rust/mx-multiplexer
//! commits: prost-build run on multiplexer/Multiplexer.proto and the
//! multiplexer/Logging.proto it imports, with the system's protoc (the
//! repository's build needs it anyway), `bytes` fields as `bytes::Bytes` so
//! that a payload decodes as a slice of its frame. Run it from rust/:
//! `cargo run --manifest-path codegen/Cargo.toml`, or with `--check` to say
//! whether the committed files are what it would write, which format.sh
//! runs.
//!
//! Each file it writes opens with a comment naming the .proto files and
//! their CRC-32s, so that rust/mx-multiplexer's Bazel test notices a .proto
//! changed since, with no Rust toolchain at hand; prost's own output follows
//! as it is. Nobody who builds the crate needs protoc or this generator: the
//! output is committed and the crate include!s it, which rustfmt leaves
//! alone.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// One set of .proto files compiled together and the directory their
/// generated files are committed to.
struct Target {
    protos: &'static [&'static str],
    out_dir: &'static str,
}

const TARGETS: &[Target] = &[Target {
    protos: &["multiplexer/Multiplexer.proto", "multiplexer/Logging.proto"],
    out_dir: "rust/mx-multiplexer/src/proto",
}];

/// The repository's root, two levels above this crate's manifest: every
/// path above is relative to it.
fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// The CRC-32 of `bytes`, zlib's, as the repository's fingerprints are,
/// computed bit by bit: a few kilobytes of .proto, once.
fn crc32(bytes: &[u8]) -> u32 {
    let mut crc = 0xFFFF_FFFFu32;
    for byte in bytes {
        crc ^= u32::from(*byte);
        for _ in 0..8 {
            crc = (crc >> 1) ^ (0xEDB8_8320 & (0u32.wrapping_sub(crc & 1)));
        }
    }
    crc ^ 0xFFFF_FFFF
}

/// The comment every generated file opens with: what it is and the inputs'
/// fingerprints, one `// input PATH CRC` line each, which the Bazel test
/// compares with the .proto files as they are.
fn header(target: &Target) -> std::io::Result<String> {
    let mut text = format!(
        "// Generated by rust/codegen from {} with prost-build; do not edit, run it again.\n//\n",
        target.protos.join(" and ")
    );
    for proto in target.protos {
        text.push_str(&format!("// input {} {:08x}\n", proto, crc32(&fs::read(root().join(proto))?)));
    }
    text.push('\n');
    Ok(text)
}

/// Generates `target` into a scratch directory and returns each file's name
/// and text, its header included.
fn generate(target: &Target, scratch: &Path) -> Result<Vec<(String, String)>, Box<dyn std::error::Error>> {
    fs::create_dir_all(scratch)?;
    let mut config = prost_build::Config::new();
    config.bytes(["."]);
    config.out_dir(scratch);
    let protos: Vec<PathBuf> = target.protos.iter().map(|proto| root().join(proto)).collect();
    config.compile_protos(&protos, &[root()])?;
    let header = header(target)?;
    let mut files = Vec::new();
    let mut names: Vec<PathBuf> =
        fs::read_dir(scratch)?.map(|entry| entry.map(|entry| entry.path())).collect::<Result<_, _>>()?;
    names.sort();
    for path in names {
        let name = path.file_name().and_then(|name| name.to_str()).ok_or("a file name that is not UTF-8")?.to_string();
        files.push((name, header.clone() + &fs::read_to_string(&path)?));
    }
    Ok(files)
}

/// Writes every target, or with `check` compares it with what is committed;
/// false when something is stale (or, writing, never).
fn run(check: bool) -> Result<bool, Box<dyn std::error::Error>> {
    let mut fresh = true;
    for (index, target) in TARGETS.iter().enumerate() {
        let scratch = std::env::temp_dir().join(format!("mx-codegen-{}-{}", std::process::id(), index));
        let files = generate(target, &scratch);
        let _ = fs::remove_dir_all(&scratch);
        for (name, text) in files? {
            let shown = Path::new(target.out_dir).join(&name);
            let committed = root().join(&shown);
            if check {
                if fs::read_to_string(&committed).ok().as_deref() != Some(text.as_str()) {
                    eprintln!(
                        "{} is stale: run cargo run --manifest-path codegen/Cargo.toml in rust/",
                        shown.display()
                    );
                    fresh = false;
                }
            } else {
                fs::write(&committed, text)?;
                println!("{}", shown.display());
            }
        }
    }
    Ok(fresh)
}

fn main() -> ExitCode {
    let check = std::env::args().skip(1).any(|argument| argument == "--check");
    match run(check) {
        Ok(true) => ExitCode::SUCCESS,
        Ok(false) => ExitCode::FAILURE,
        Err(error) => {
            eprintln!("codegen: {error}");
            ExitCode::FAILURE
        }
    }
}
